// Runs the real Electron preload, renderer and IPC against an in-memory API stub.
const { app, BrowserWindow, session } = require('electron');
const assert = require('node:assert/strict');
app.commandLine.appendSwitch('smoke-test');
delete process.env.OPENAI_API_KEY;
delete process.env.GEMINI_API_KEY;
delete process.env.GROQ_API_KEY;
let mode = 'ok';
let calls = [];
global.fetch = async (url, options) => {
  calls.push({ url, options });
  if (mode === 'unauthorized') return { ok: false, status: 401, json: async () => ({}) };
  if (mode === 'quota') return { ok: false, status: 429, json: async () => ({}) };
  if (mode === 'pending') return new Promise((resolve, reject) => options.signal.addEventListener('abort', () => reject(new Error('aborted')), { once: true }));
  if (url.includes('generativelanguage.googleapis.com')) return { ok: true, json: async () => ({ candidates: [{ finishReason: 'STOP', content: { parts: [{ text: JSON.stringify({ question: 'Вопрос из аудио', answer: 'Ответ Gemini.' }) }] } }] }) };
  if (url.endsWith('/chat/completions')) return { ok: true, json: async () => ({ choices: [{ finish_reason: mode === 'truncated' ? 'length' : 'stop', message: { content: 'Ответ Groq.', reasoning: 'Never display this' } }] }) };
  return { ok: true, json: async () => url.endsWith('/transcriptions')
    ? { text: 'Чем отличаются useEffect и useLayoutEffect?' }
    : { output: [{ content: [{ type: 'output_text', text: 'Тестовый краткий ответ.' }] }] } };
};
require('../main.cjs');
const deadline = setTimeout(() => { console.error('Smoke test timed out'); app.exit(1); }, 20000);
app.whenReady().then(async () => {
  try {
    session.fromPartition('assistant-api').fetch = global.fetch;
    const win = BrowserWindow.getAllWindows()[0];
    win.webContents.on('console-message', event => console.log('Renderer:', event.message));
    await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    const run = async js => { try { return await win.webContents.executeJavaScript(js); } catch (error) { throw new Error(`Renderer evaluation failed: ${js}: ${error.message}`); } };
    assert.equal(await run('typeof window.assistant.ask'), 'function');
    assert.equal(await run('typeof window.AudioTools.encodeWav'), 'function');
    assert.equal(await run("document.getElementById('provider').value"), 'groq');
    const missing = await run("window.assistant.ask({ text: 'React?' })");
    assert.match(missing.error, /ключ/);
    await run("window.assistant.settings({ provider: 'openai', key: 'fake-test-key', transcriptionModel: 'gpt-transcribe', answerModel: 'gpt-4.1-mini' })");
    await run("document.getElementById('question').value = 'Что такое reconciliation?'; ask(false)");
    assert.equal(await run("document.getElementById('answer').textContent.trim()"), 'Тестовый краткий ответ.');
    const audio = await run("window.assistant.ask({ audio: window.AudioTools.encodeWav(new Float32Array(24000), 24000) })");
    assert.match(audio.transcript, /useEffect/);
    assert.equal(calls.length, 3);
    assert.equal(calls[1].options.body.get('file').type, 'audio/wav');
    assert.equal(JSON.parse(calls[2].options.body).store, false);
    mode = 'unauthorized';
    assert.match((await run("window.assistant.ask({ text: 'test' })")).error, /ключ не принят/);
    mode = 'pending';
    const cancelled = await run("(async () => { const pending = window.assistant.ask({ text: 'test' }); setTimeout(() => window.assistant.cancel(), 50); return pending; })()");
    assert.equal(cancelled.error, 'Запрос отменён.');
    mode = 'ok';
    assert.equal((await run("window.assistant.ask({ text: 'test' })")).answer, 'Тестовый краткий ответ.');
    await run("window.assistant.settings({ provider: 'gemini' })");
    assert.match((await run("window.assistant.ask({ text: 'test' })")).error, /ключ/);
    await run("window.assistant.settings({ key: 'fake-gemini-key', proxy: 'http://127.0.0.1:9697' })");
    assert.equal(await session.fromPartition('assistant-api').resolveProxy('https://generativelanguage.googleapis.com'), 'PROXY 127.0.0.1:9697');
    const before = calls.length;
    const gemini = await run("window.assistant.ask({ audio: window.AudioTools.encodeWav(new Float32Array(24000), 24000), context: 'React' })");
    assert.equal(gemini.answer, 'Ответ Gemini.');
    assert.equal(calls.length, before + 1, 'Gemini audio must use a single request');
    const request = calls.at(-1);
    assert.equal(request.options.headers['x-goog-api-key'], 'fake-gemini-key');
    assert.equal(request.options.headers.Authorization, undefined, 'Never send OpenAI key to Gemini');
    const payload = JSON.parse(request.options.body);
    assert.equal(payload.contents[0].parts[1].inlineData.mimeType, 'audio/wav');
    assert.equal(Buffer.from(payload.contents[0].parts[1].inlineData.data, 'base64').subarray(0, 4).toString(), 'RIFF');
    await run("document.getElementById('provider').value = 'gemini'; document.getElementById('provider').dispatchEvent(new Event('change')); ask(false)");
    assert.match(await run("document.getElementById('status').textContent"), /Применить/);
    assert.equal(calls.length, before + 1);
    await run("window.assistant.settings({ provider: 'groq' })");
    assert.match((await run("window.assistant.ask({ text: 'React?' })")).error, /ключ/);
    await run("document.getElementById('provider').value = 'groq'; document.getElementById('provider').dispatchEvent(new Event('change')); document.getElementById('key').value = 'fake-groq-key'; document.getElementById('save').onclick()");
    assert.equal(await run("document.getElementById('key').value"), '');
    assert.match(await run("document.getElementById('providerNotice').textContent"), /Groq/);
    await run("ask(false)");
    assert.equal(await run("document.getElementById('answer').textContent.trim()"), 'Ответ Groq.');
    const groqStart = calls.length;
    const groqAudio = await run("window.assistant.ask({ audio: window.AudioTools.encodeWav(new Float32Array(24000), 24000) })");
    assert.equal(groqAudio.answer, 'Ответ Groq.');
    assert.equal(calls.length, groqStart + 2);
    const [stt, chat] = calls.slice(groqStart);
    assert.equal(stt.url, 'https://api.groq.com/openai/v1/audio/transcriptions');
    assert.equal(stt.options.body.get('model'), 'whisper-large-v3-turbo');
    assert.equal(chat.url, 'https://api.groq.com/openai/v1/chat/completions');
    for (const request of [stt, chat]) {
      assert.equal(request.options.headers.Authorization, 'Bearer fake-groq-key');
      assert.equal(request.options.headers['x-goog-api-key'], undefined);
    }
    const groqPayload = JSON.parse(chat.options.body);
    assert.equal(groqPayload.model, 'openai/gpt-oss-120b');
    assert.equal(groqPayload.include_reasoning, false);
    assert.match(groqPayload.messages[1].content, /useEffect/);
    mode = 'quota';
    assert.match((await run("window.assistant.ask({ text: 'test' })")).error, /Квота/);
    mode = 'truncated';
    assert.match((await run("window.assistant.ask({ text: 'test' })")).error, /оборвал/);
    mode = 'ok';
    await run("document.getElementById('checkConnection').onclick()");
    assert.match(await run("document.getElementById('status').textContent"), /ключ принят/);
    assert.equal(calls.at(-1).url, 'https://api.groq.com/openai/v1/models');
    assert.equal(calls.at(-1).options.method, 'GET');
    mode = 'unauthorized';
    assert.match((await run('window.assistant.checkConnection()')).error, /ключ не принят/);
    const markdown = '**Жирный** и *курсив*\n\n- пункт\n\n```json\n{"scripts":{"test":"vitest"}}\n```\n\n```unknown-language\n<a>literal code</a>\n```\n\n<img src=x onerror="window.markdownUnsafe=true"><script>window.markdownUnsafe=true</script><iframe src="https://example.com"></iframe><input id="key"><a href="javascript:alert(1)">link</a>';
    await run(`window.renderAnswer(${JSON.stringify(markdown)})`);
    assert.equal(await run("document.querySelector('#answer strong').textContent"), 'Жирный');
    assert.equal(await run("document.querySelector('#answer em').textContent"), 'курсив');
    assert.equal(await run("document.querySelectorAll('#answer li').length"), 1);
    assert.ok(await run("document.querySelector('#answer code.language-json .hljs-attr') !== null"));
    assert.equal(await run("document.querySelector('#answer code.language-unknown-language').textContent.trim()"), '<a>literal code</a>');
    assert.equal(await run("document.querySelectorAll('#answer script, #answer img, #answer iframe, #answer input, #answer [onclick], #answer [onerror], #answer [href]').length"), 0);
    assert.equal(await run('window.markdownUnsafe === true'), false);
    console.log('PASS: UI, providers, networking, Markdown formatting, code highlighting and unsafe HTML removal. No real API requests or audio capture.');
    clearTimeout(deadline); app.exit(0);
  } catch (error) { console.error(error); clearTimeout(deadline); app.exit(1); }
});
